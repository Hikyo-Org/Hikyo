// Command omitzero writes api/omitzero-overlay.yaml, the OpenAPI Overlay that
// oapi-codegen applies before generating api/apigen. It runs via
// `go run ./api/omitzero` from the repository root and is drift-checked by
// this package's test, because the CI "generated code is fresh" step runs only
// oapi-codegen against the committed overlay.
//
// Why: oapi-codegen tags every optional property `json:"x,omitempty"`. Under
// encoding/json/v2, omitempty also drops a non-nil pointer to "", [] or {}, so
// a CLI clear flag (`--description ""`, `--clear-bypassers`) would be omitted
// from the request body, and a present-but-empty field would vanish from CLI
// `-o json` output. `omitzero` omits a nil pointer or interface, or a
// pointed-to value whose IsZero() is true (only time.Time here), and is
// otherwise byte-identical to v1 omitempty under both v1 (Go 1.24+) and v2.
// The overlay sets `x-omitempty: false` and `x-omitzero: true` on exactly the
// properties oapi-codegen would give omitempty.
package main

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"strings"

	"gopkg.in/yaml.v3"
)

const (
	specPath    = "api/openapi.yaml"
	overlayPath = "api/omitzero-overlay.yaml"
	header      = "# Generated by `go run ./api/omitzero` from api/openapi.yaml; DO NOT EDIT.\n" +
		"# oapi-codegen applies it (api/oapi-codegen.yaml, output-options.overlay) so\n" +
		"# optional properties get `omitzero` instead of `omitempty`; see\n" +
		"# api/omitzero/main.go. Regenerate after every api/openapi.yaml change:\n" +
		"#   go run ./api/omitzero\n"
)

type overlay struct {
	Overlay string       `yaml:"overlay"`
	Info    overlayInfo  `yaml:"info"`
	Actions []overlayAct `yaml:"actions"`
}

type overlayInfo struct {
	Title   string `yaml:"title"`
	Version string `yaml:"version"`
}

type overlayAct struct {
	Target string         `yaml:"target"`
	Update map[string]any `yaml:"update"`
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "omitzero:", err)
		os.Exit(1)
	}
}

func run() error {
	spec, err := os.ReadFile(specPath)
	if err != nil {
		return err
	}
	out, err := generate(spec)
	if err != nil {
		return err
	}
	return os.WriteFile(overlayPath, out, 0o644) //nolint:gosec // repository source file, not a secret
}

// generate renders the overlay for one OpenAPI document.
func generate(spec []byte) ([]byte, error) {
	var doc yaml.Node
	if err := yaml.Unmarshal(spec, &doc); err != nil {
		return nil, fmt.Errorf("parse %s: %w", specPath, err)
	}
	if len(doc.Content) != 1 {
		return nil, errors.New("openapi document is empty")
	}
	w := &walker{root: doc.Content[0]}
	if err := w.walk(w.root, "$", false); err != nil {
		return nil, err
	}
	ov := overlay{
		Overlay: "1.0.0",
		Info:    overlayInfo{Title: "omitzero for optional properties", Version: "1.0.0"},
		Actions: w.actions,
	}
	var buf bytes.Buffer
	buf.WriteString(header)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(ov); err != nil {
		return nil, err
	}
	return buf.Bytes(), enc.Close()
}

type walker struct {
	root    *yaml.Node
	actions []overlayAct
}

// walk visits every schema-bearing mapping. propMap is true when n is the
// `properties` mapping itself, whose keys are property names, not keywords.
func (w *walker) walk(n *yaml.Node, path string, propMap bool) error {
	switch n.Kind {
	case yaml.AliasNode:
		return fmt.Errorf("%s: YAML aliases are not supported", path)
	case yaml.SequenceNode:
		for i, c := range n.Content {
			if err := w.walk(c, fmt.Sprintf("%s[%d]", path, i), false); err != nil {
				return err
			}
		}
	case yaml.MappingNode:
		if !propMap {
			if err := w.emit(n, path); err != nil {
				return err
			}
		}
		for i := 0; i < len(n.Content); i += 2 {
			k, v := n.Content[i].Value, n.Content[i+1]
			// Literal values and extensions never hold schemas.
			if !propMap && (k == "example" || k == "examples" || k == "default" || k == "const" || k == "enum" || strings.HasPrefix(k, "x-")) {
				continue
			}
			if k == "parameters" && !propMap {
				w.emitParams(v, path+"['parameters']")
			}
			if err := w.walk(v, path+"['"+quote(k)+"']", k == "properties" && !propMap); err != nil {
				return err
			}
		}
	}
	return nil
}

// emit records one action for n when it is a schema whose properties include
// optional ones. The omit-empty rule mirrors oapi-codegen v2.8.0
// pkg/codegen/schema.go shouldOmitEmpty: not required, or readOnly/writeOnly.
func (w *walker) emit(n *yaml.Node, path string) error {
	props := mapGet(n, "properties")
	if props == nil || props.Kind != yaml.MappingNode {
		return nil
	}
	required := map[string]bool{}
	if req := mapGet(n, "required"); req != nil && req.Kind == yaml.SequenceNode {
		for _, r := range req.Content {
			required[r.Value] = true
		}
	}
	var names []string
	for i := 0; i < len(props.Content); i += 2 {
		name, schema := props.Content[i].Value, props.Content[i+1]
		if !required[name] || w.flagged(schema, "readOnly") || w.flagged(schema, "writeOnly") {
			names = append(names, "'"+quote(name)+"'")
		}
	}
	if len(names) == 0 {
		return nil
	}
	w.actions = append(w.actions, overlayAct{
		Target: path + "['properties'][" + strings.Join(names, ",") + "]",
		Update: omitzeroUpdate(),
	})
	return nil
}

// emitParams records one action for the optional non-path parameters of an
// operation or path item (a sequence) or of components.parameters (a mapping).
// Parameter structs take their tags from extensions on the parameter object.
// Parameters that are $refs are covered at their components.parameters entry.
func (w *walker) emitParams(params *yaml.Node, path string) {
	optional := func(p *yaml.Node) bool {
		in, req := mapGet(p, "in"), mapGet(p, "required")
		return in != nil && in.Value != "path" && mapGet(p, "$ref") == nil && (req == nil || req.Value != "true")
	}
	var sels []string
	switch params.Kind {
	case yaml.SequenceNode:
		for i, p := range params.Content {
			if optional(p) {
				sels = append(sels, fmt.Sprint(i))
			}
		}
	case yaml.MappingNode:
		for i := 0; i < len(params.Content); i += 2 {
			if optional(params.Content[i+1]) {
				sels = append(sels, "'"+quote(params.Content[i].Value)+"'")
			}
		}
	}
	if len(sels) > 0 {
		w.actions = append(w.actions, overlayAct{Target: path + "[" + strings.Join(sels, ",") + "]", Update: omitzeroUpdate()})
	}
}

func omitzeroUpdate() map[string]any {
	return map[string]any{"x-omitempty": false, "x-omitzero": true}
}

// flagged reports whether a property schema (following local $refs) sets key.
func (w *walker) flagged(schema *yaml.Node, key string) bool {
	for range 8 {
		if v := mapGet(schema, key); v != nil {
			return v.Value == "true"
		}
		ref := mapGet(schema, "$ref")
		if ref == nil || !strings.HasPrefix(ref.Value, "#/") {
			return false
		}
		schema = w.root
		for _, seg := range strings.Split(ref.Value[2:], "/") {
			if schema = mapGet(schema, strings.ReplaceAll(strings.ReplaceAll(seg, "~1", "/"), "~0", "~")); schema == nil {
				return false
			}
		}
	}
	return false
}

func mapGet(n *yaml.Node, key string) *yaml.Node {
	if n == nil || n.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i < len(n.Content); i += 2 {
		if n.Content[i].Value == key {
			return n.Content[i+1]
		}
	}
	return nil
}

// quote escapes a name for a single-quoted JSONPath bracket selector.
func quote(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, `\`, `\\`), `'`, `\'`)
}
