import assert from 'node:assert/strict';
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import test from 'node:test';

const header = '// This file is auto-generated by @hey-api/openapi-ts\n\n';
const templates = {
  'client/client.gen.ts': 'JSON.parse(text); JSON.parse(textError);\n',
  'core/serverSentEvents.gen.ts': 'JSON.parse(rawData);\n',
};

for (const target of Object.keys(templates)) {
  test(`parser installation rejects a missing import anchor in ${target}`, () => {
    const root = mkdtempSync(join(tmpdir(), 'hikyo-parser-installer-'));
    try {
      mkdirSync(join(root, 'scripts'));
      const script = join(root, 'scripts/install-json-parser.ts');
      copyFileSync(new URL('../scripts/install-json-parser.ts', import.meta.url), script);
      for (const [path, calls] of Object.entries(templates)) {
        const directory = path.slice(0, path.indexOf('/'));
        mkdirSync(join(root, 'src/generated', directory), { recursive: true });
        // A blank line inside a changed block header must not become an import.
        writeFileSync(join(root, 'src/generated', path),
          (path === target ? '/* changed header\n\nend */\n' : header) + calls);
      }
      const before = readFileSync(join(root, 'src/generated', target), 'utf8');
      const result = spawnSync(process.execPath, ['--experimental-strip-types', script], { encoding: 'utf8' });
      assert.notEqual(result.status, 0);
      assert.match(result.stderr, /Generated JSON parser template changed:.*import anchor/);
      assert.equal(readFileSync(join(root, 'src/generated', target), 'utf8'), before);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });
}
