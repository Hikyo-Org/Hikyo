// embed-compatibility moves release claims into generated source so the complete
// declaration never travels through an exec argument or environment variable.
package main

import (
	"encoding/base64"
	"fmt"
	"os"

	"github.com/Hikyo-Org/hikyo/internal/releaseidentity"
	"github.com/Hikyo-Org/hikyo/internal/upgradecompat"
)

func main() {
	if err := generate(os.Getenv("HIKYO_COMPATIBILITY_PATH"), os.Getenv("HIKYO_COMPATIBILITY_SHA256"), os.Getenv("HIKYO_UPDATE_CHANNEL"), "internal/buildcompat/declaration_generated.go"); err != nil {
		fmt.Fprintln(os.Stderr, "embed-compatibility:", err)
		os.Exit(1)
	}
}

func generate(path, digest, channel, output string) error {
	// Remove a previous build's stamp even if this invocation fails validation.
	if err := os.Remove(output); err != nil && !os.IsNotExist(err) {
		return err
	}
	if path == "" {
		if digest != "" || (channel != "" && channel != "off") {
			return fmt.Errorf("release compatibility path is required")
		}
		return nil // Unstamped CI snapshots remain update-channel off.
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if base64.StdEncoding.EncodedLen(len(raw)) > 6<<20 {
		return fmt.Errorf("release compatibility declaration exceeds embedded size limit")
	}
	if releaseidentity.Digest(digest).Validate() != nil || string(releaseidentity.Hash(raw)) != digest {
		return fmt.Errorf("release compatibility digest mismatch")
	}
	if _, err := upgradecompat.Parse(raw); err != nil {
		return err
	}
	// An explicit linker stamp still wins for existing subprocess test fixtures.
	source := fmt.Sprintf("// Code generated by scripts/release/embed-compatibility; DO NOT EDIT.\npackage buildcompat\n\nfunc init() { if encodedDeclaration == \"\" { encodedDeclaration = %q } }\n", base64.StdEncoding.EncodeToString(raw))
	return os.WriteFile(output, []byte(source), 0o600)
}
